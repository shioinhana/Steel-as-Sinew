package com.actioncombat.combat;

/**
 * Per-weapon animation set and combat tuning. Category is derived from what the
 * player holds: a sword in both hands = DOUBLE, otherwise SINGLE.
 * All names here must exist in the matching geckolib asset files (checked by
 * tools/check_assets.mjs and AssetBakeSmokeTest).
 * <p>
 * Dual-wield keeps the left/right hand-rest gates. The rapier (SINGLE) uses its
 * own pattern: left click cycles {@code attack1}–{@code attack4}, right click
 * is a dedicated thrust. After a successful parry, both buttons together play
 * {@code attack_dual}.
 */
public enum WeaponCategory {
    SPEAR(
            "player_longsword", "third_person_spear",
            "static_idle", "inspect", "run_start", "run_hold", "run_end",
            "draw", "put_away", "defend_upper", "aiming_upper",
            "walk_start", "walk_hold", "walk_end", "crouch_idle", "jump", "fall", "hurt_upper",
            new SwingChain(new String[]{"attack1", "attack3"},
                    new float[]{0.4F, 0.4F}, new float[]{6.0F, 8.0F}),
            new SwingChain(new String[]{"attack2", "attack4"},
                    new float[]{0.4F, 0.4F}, new float[]{2.0F, 2.0F})),
    SINGLE(
            "player_longsword", "third_person_singlesword",
            "static_idle", "inspect", "run_start", "run_hold", "run_end",
            "draw", "put_away", "defend_upper", "aiming_upper",
            "walk_start", "walk_hold", "walk_end", "crouch_idle", "jump", "fall", "hurt_upper",
            // hand 0 = left, hand 1 = right. Left slash then right slash.
            // 左手左砍 attack1, 右手左砍 attack3, 左手右砍 attack2, 右手右砍 attack4
            new SwingChain(
                    new String[]{"attack1", "attack3"},
                    new float[]{0.4F, 0.4F},
                    new float[]{6.0F, 7.0F}),
            new SwingChain(
                    new String[]{"attack2", "attack4"},
                    new float[]{0.4F, 0.4F},
                    new float[]{6.0F, 9.0F})),
    DOUBLE(
            "player_doublesword", "third_person_doublesword",
            "static_idle", "inspect", "run_start", "run_hold", "run_end",
            "draw", "put_away", "defend_upper", "aiming_upper",
            "walk_start", "walk_hold", "walk_end", "crouch_idle", "jump", "fall", "hurt_upper",
            // 左手左砍 attack_1, 右手左砍 attack2, 左手右砍 attack4, 右手右砍 attack3
            new SwingChain(
                    new String[]{"attack_1", "attack2"},
                    new float[]{0.4F, 0.4F},
                    new float[]{4.0F, 4.0F}),
            new SwingChain(
                    new String[]{"attack4", "attack3"},
                    new float[]{0.4F, 0.4F},
                    new float[]{5.0F, 4.0F})),
    /**
     * Two-handed katana stance (左手拔刀). Reuses the longsword model; the katana
     * animation set is authored by {@code tools/generate_katana.mjs}. Attacks are
     * command-type: they only strike the locked target.
     */
    KATANA(
            "player_longsword", "third_person_katana",
            "static_idle", "inspect", "run_start", "run_hold", "run_end",
            "draw", "put_away", "defend_upper", "aiming_upper",
            "walk_start", "walk_hold", "walk_end", "crouch_idle", "jump", "fall", "hurt_upper",
            // 双手持剑: 左链 下劈→上挑, 右链 横斩→突刺
            new SwingChain(
                    new String[]{"attack1", "attack3"},
                    new float[]{0.4F, 0.4F},
                    new float[]{8.0F, 9.0F}),
            new SwingChain(
                    new String[]{"attack2", "attack4"},
                    new float[]{0.4F, 0.4F},
                    new float[]{8.0F, 10.0F}));

    /** One side of the alternating combo: clip names plus their tuning, by chain index. */
    public record SwingChain(String[] clips, float[] durations, float[] damages) {
        public int length() {
            return clips.length;
        }

        public String clip(int index) {
            return index >= 0 && index < clips.length ? clips[index] : null;
        }

        public float duration(int index) {
            return durations[Math.floorMod(index, durations.length)];
        }

        public float damage(int index) {
            return damages[Math.floorMod(index, damages.length)];
        }
    }

    /** Model file id under geckolib/models (without .geo.json). */
    public final String modelId;
    /** Animation file id under geckolib/animations (without .animation.json). */
    public final String animationsId;
    public final String idle;
    public final String inspect;
    public final String runStart;
    public final String runHold;
    public final String runEnd;
    public final String draw;
    public final String putAway;
    /** Guard stance held while blocking (thenPlayAndHold). */
    public final String defend;
    /** Charge stance held while aiming (thenPlayAndHold). */
    public final String aiming;
    // locomotion + reaction clips generated by tools/generate_locomotion.mjs
    public final String walkStart;
    public final String walkHold;
    public final String walkEnd;
    public final String crouchIdle;
    public final String jump;
    public final String fall;
    public final String hurt;
    private final SwingChain left;
    private final SwingChain right;

    WeaponCategory(String modelId, String animationsId,
                   String idle, String inspect, String runStart, String runHold, String runEnd,
                   String draw, String putAway, String defend, String aiming,
                   String walkStart, String walkHold, String walkEnd, String crouchIdle,
                   String jump, String fall, String hurt,
                   SwingChain left, SwingChain right) {
        this.modelId = modelId;
        this.animationsId = animationsId;
        this.idle = idle;
        this.inspect = inspect;
        this.runStart = runStart;
        this.runHold = runHold;
        this.runEnd = runEnd;
        this.draw = draw;
        this.putAway = putAway;
        this.defend = defend;
        this.aiming = aiming;
        this.walkStart = walkStart;
        this.walkHold = walkHold;
        this.walkEnd = walkEnd;
        this.crouchIdle = crouchIdle;
        this.jump = jump;
        this.fall = fall;
        this.hurt = hurt;
        this.left = left;
        this.right = right;
    }

    public SwingChain chain(SwingSide side) {
        return side == SwingSide.RIGHT ? right : left;
    }

    public static final String DUAL_ATTACK = "attack_dual";

    /** Clip for a slash direction and which hand is swinging (0 = left, 1 = right). */
    public String attackAnim(SwingSide side, int hand) {
        return chain(side).clip(hand);
    }

    /**
     * Upper-body overlay of {@link #attackAnim}: same timing, no leg bones, so a
     * walk cycle can keep playing underneath.
     */
    public String attackOverlay(SwingSide side, int hand) {
        String clip = attackAnim(side, hand);
        return clip == null ? null : this == SPEAR ? clip : clip + "_upper";
    }

    public String dualOverlay() {
        return DUAL_ATTACK + "_upper";
    }

    public float attackDuration(SwingSide side, int hand) {
        return com.actioncombat.CombatConstants.ATTACK_DURATION_SECONDS;
    }

    public float attackDamage(SwingSide side, int hand) {
        return chain(side).damage(hand);
    }

    public float dualDuration() {
        return com.actioncombat.CombatConstants.ATTACK_DURATION_SECONDS;
    }

    /** Every attack clip in both chains plus the parry dual cut. */
    public String[] allAttacks() {
        String[] all = new String[left.length() + right.length() + 1];
        System.arraycopy(left.clips(), 0, all, 0, left.length());
        System.arraycopy(right.clips(), 0, all, left.length(), right.length());
        all[all.length - 1] = DUAL_ATTACK;
        return all;
    }

    /** Locomotion and reaction clips, for asset verification. */
    public String[] locomotionClips() {
        return new String[]{
                walkStart, walkHold, walkHold + "_left", walkHold + "_right", walkHold + "_back",
                walkEnd, crouchIdle, "crouch_walk", "crouch_walk_left", "crouch_walk_right", "crouch_walk_back",
                runHold, runHold + "_left", runHold + "_right", runHold + "_back",
                "jump_start", jump, fall, hurt};
    }

    /**
     * Walk/run cycle for the current body-relative move vector.
     * Strafe uses {@code *_left}/{@code *_right}, backing uses {@code *_back}.
     */
    public String gaitClip(boolean running, float forward, float strafe) {
        return gaitClip(running, false, forward, strafe);
    }

    public String gaitClip(boolean running, boolean crouching, float forward, float strafe) {
        String base = crouching ? "crouch_walk" : (running ? runHold : walkHold);
        float along = Math.abs(forward);
        float side = Math.abs(strafe);
        if (side > 0.08F && side >= along * 0.85F) {
            return base + (strafe > 0.0F ? "_left" : "_right");
        }
        if (forward < -0.08F) {
            return base + "_back";
        }
        return base;
    }

    public static WeaponCategory of(net.minecraft.world.entity.LivingEntity player) {
        if (player.getMainHandItem().is(net.minecraft.tags.ItemTags.SPEARS)) return SPEAR;
        return of(player.getMainHandItem().is(net.minecraft.tags.ItemTags.SWORDS)
                && player.getOffhandItem().is(net.minecraft.tags.ItemTags.SWORDS));
    }

    public static WeaponCategory of(boolean dualWield) {
        return dualWield ? DOUBLE : SINGLE;
    }
}
